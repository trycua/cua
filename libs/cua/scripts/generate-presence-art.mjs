#!/usr/bin/env node

/**
 * Generate `libs/cua/typescript/src/spaces/cursorArt.ts` from the shared
 * presence cursor art (`crates/cua-spaces/assets/presence-cursors.json`, the
 * one source every client draws from), and fail rather than rot when the
 * committed copy drifts. Run by generate-uniffi-bindings.mjs whenever it
 * generates or checks the TypeScript binding.
 *
 * Usage: node generate-presence-art.mjs [--check]
 */

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const cuaRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const source = join(cuaRoot, "crates/cua-spaces/assets/presence-cursors.json")
const target = join(cuaRoot, "typescript/src/spaces/cursorArt.ts")
const check = process.argv.includes("--check")

const doc = JSON.parse(readFileSync(source, "utf8"))
const shapes = Object.keys(doc.shapes)
const entries = shapes
  .map((name) => {
    const s = doc.shapes[name]
    return `  ${name}: { hotspot: [${s.hotspot[0]}, ${s.hotspot[1]}] as const, d: ${JSON.stringify(s.d)} },`
  })
  .join("\n")

const output = `// Generated by libs/cua/scripts/generate-presence-art.mjs from
// libs/cua/crates/cua-spaces/assets/presence-cursors.json. Do not edit.

/** A presence cursor shape (the names of \`cua.env.v1.CursorShape\`). */
export type CursorShapeName =
${shapes.map((n) => `  | ${JSON.stringify(n)}`).join("\n")}

/** Every shape, in wire order. */
export const CURSOR_SHAPES: readonly CursorShapeName[] = Object.freeze([
${shapes.map((n) => `  ${JSON.stringify(n)},`).join("\n")}
])

/** One shape's art: an SVG path (absolute M, L, C, Z; nonzero fill) and its hot spot. */
export interface CursorArtShape {
  hotspot: readonly [number, number]
  d: string
}

/** The shared presence cursor art: fill with the participant's color over the outline. */
export const CURSOR_ART: {
  canvas: number
  outline: { color: string; width: number }
  shapes: Readonly<Record<CursorShapeName, CursorArtShape>>
} = Object.freeze({
  canvas: ${doc.canvas},
  outline: Object.freeze({ color: ${JSON.stringify(doc.outline.color)}, width: ${doc.outline.width} }),
  shapes: Object.freeze({
${entries.replace(/^/gm, "  ")}
  }),
})

/** Whether \`name\` is a known shape. */
export function isCursorShape(name: unknown): name is CursorShapeName {
  return typeof name === "string" && Object.prototype.hasOwnProperty.call(CURSOR_ART.shapes, name)
}

/** The art for \`shape\`; unknown names get the arrow. */
export function cursorArt(shape: string): CursorArtShape {
  return isCursorShape(shape) ? CURSOR_ART.shapes[shape] : CURSOR_ART.shapes.arrow
}

/**
 * A standalone SVG of \`shape\` filled with \`color\`, \`size\` pixels square.
 * The hot spot is at \`cursorArt(shape).hotspot * size / CURSOR_ART.canvas\`.
 */
export function cursorArtSvg(shape: string, color: string, size: number = CURSOR_ART.canvas): string {
  const a = cursorArt(shape)
  const c = CURSOR_ART.canvas
  const fill = /^#[0-9a-fA-F]{3,8}$/.test(color) ? color : "#3b82f6"
  return (
    \`<svg xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" viewBox="0 0 \${c} \${c}">\` +
    \`<path d="\${a.d}" fill="\${fill}" stroke="\${CURSOR_ART.outline.color}" stroke-width="\${CURSOR_ART.outline.width}" stroke-linejoin="round" paint-order="stroke"/></svg>\`
  )
}
`

if (check) {
  let current = ""
  try {
    current = readFileSync(target, "utf8")
  } catch {}
  if (current !== output) {
    console.error(`stale presence cursor art: ${target}\n  run: node libs/cua/scripts/generate-presence-art.mjs`)
    process.exit(1)
  }
  console.log("Presence cursor art is up to date.")
} else {
  writeFileSync(target, output)
  console.log(`Wrote ${target}`)
}
