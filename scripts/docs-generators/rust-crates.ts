/**
 * Rust crate reference generator.
 *
 * Builds rustdoc JSON for the public cua crates with a pinned nightly (the
 * `scripts/docs-generators/rustdoc-json` tool owns the pin and the matching
 * `rustdoc-types`), then renders `reference/cua-sdk/rust/*.mdx`: a few pages
 * per crate, grouped by source module, with an anchor per item.
 *
 * Usage:
 *   pnpm --dir docs docs:generate:cua-rust            # build JSON + write pages
 *   pnpm --dir docs docs:check:cua-rust               # drift check (CI)
 *   npx tsx scripts/docs-generators/rust-crates.ts --dump FILE [--check]
 *                                                     # render an existing dump
 *
 * `rust/index.mdx` (crates, dependency and stability) is rendered from
 * headers/cua-sdk/rust/index.md.
 */

