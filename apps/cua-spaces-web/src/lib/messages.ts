/** A core message as text: its English with the variables filled in. */
export function messageText(msg: Msg): string {
  const text = MESSAGES[msg.code] ?? msg.code;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => msg.vars[name] ?? whole);
}

/** `value` with every core message in it (`{ code, vars }`) as its text. */
export function messagesAsText<T>(value: T): T {
  if (Array.isArray(value)) return value.map(messagesAsText) as T;
  if (value && typeof value === "object") {
    const o = value as Record<string, unknown>;
    if (typeof o.code === "string" && o.vars && typeof o.vars === "object" && Object.keys(o).length === 2) {
      return messageText(o as unknown as Msg) as T;
    }
    return Object.fromEntries(Object.entries(o).map(([k, v]) => [k, messagesAsText(v)])) as T;
  }
  return value;
}
