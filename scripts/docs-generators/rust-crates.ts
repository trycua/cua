const UNIFFI_GENERATOR = 'Generated by: pnpm --dir docs docs:generate:cua-sdk';

/**
 * Where the Cua SDK object pages (the cua-sdk generator) document each
 * exported name: `## \`Name\`` objects and functions, `## \`Name\` record`
 * and `## \`Name\` enum`. cua-sdk's `native` items are that same API, with a
 * Rust tab, so the crate page links there instead of repeating it.
 */
export function uniffiAnchors(dir = UNIFFI_DIR, route = UNIFFI_ROUTE): Map<string, string> {
  const out = new Map<string, string>();
  const walk = (rel: string) => {
    const abs = path.join(dir, rel);
    if (!fs.existsSync(abs)) return;
    for (const name of fs.readdirSync(abs).sort()) {
      const file = path.join(abs, name);
      if (fs.statSync(file).isDirectory()) {
        walk(path.join(rel, name));
        continue;
      }
      if (!name.endsWith('.mdx')) continue;
      const text = fs.readFileSync(file, 'utf-8');
      if (!text.slice(0, 600).includes(UNIFFI_GENERATOR)) continue;
      const page = path.join(rel, name.replace(/\.mdx$/, '')).split(path.sep).join('/').replace(/(^|\/)index$/, '');
      for (const line of text.split('\n')) {
        const m = line.match(/^##\s+`([A-Za-z_]\w*)`( record| enum)?\s*$/);
        if (m && !out.has(m[1])) out.set(m[1], `${route}/${page}#${slug(`${m[1]}${m[2] ?? ''}`)}`);
      }
    }
  };
  walk('');
  return out;
}
