"""Generate `src/e2b/sandbox/mcp.py`: the typed catalog of E2B's MCP servers.

    <venv-with-real-e2b>/bin/python tests/conformance/tools/gen_mcp_types.py \
        src/e2b/sandbox/mcp.py

Run it with the Python of an environment that has the real `e2b` (2.58 or later)
installed. It reads the catalog by introspection only (class names, key names,
annotations) and writes our own TypedDict definitions: no docstrings
or other prose of the real module is copied. `McpServer` is the TypedDict whose keys
are the catalog servers.
"""

from __future__ import annotations

import importlib
import keyword
import sys
from typing import Any, Dict, List, Tuple

HEADER = '''"""Typed catalog of the MCP servers a sandbox can start (`mcp={...}`).

Generated by `tests/conformance/tools/gen_mcp_types.py` from the key names and types
of the e2b release it was run against; do not edit by hand. Each class is a
TypedDict whose keys are the configuration fields of one server; `McpServer` maps a
server name to its configuration.

cua-e2b does not run E2B's MCP gateway (see `AsyncSandbox.create`); the catalog is
here so typed code keeps type-checking and so `mcp=` can be validated.

Annotations are evaluated (no postponed evaluation) so that `NotRequired` is seen by
`__required_keys__`; a class must therefore come after the classes it names.
"""

from typing import Any, TypedDict

from e2b._typing import NotRequired

'''


def annotation_text(value: Any) -> str:
    return getattr(value, "__forward_arg__", None) or str(value)


def strip_not_required(text: str) -> Tuple[str, bool]:
    if text.startswith("NotRequired[") and text.endswith("]"):
        return text[len("NotRequired[") : -1], False
    return text, True


def classes_in_order(mod) -> List[Tuple[str, type]]:
    return [
        (n, o)
        for n, o in vars(mod).items()
        if isinstance(o, type)
        and getattr(o, "__module__", None) == mod.__name__
        and hasattr(o, "__required_keys__")
    ]


def render(name: str, cls: type) -> str:
    annotations: Dict[str, Any] = cls.__annotations__
    items = []
    for key, ann in annotations.items():
        # The module uses postponed annotations, so `__required_keys__` cannot see
        # `NotRequired[...]`; the annotation text is the source of truth.
        text, req = strip_not_required(annotation_text(ann))
        items.append((key, text, req))
    functional = any(not k.isidentifier() or keyword.iskeyword(k) for k, _, _ in items)
    if functional:
        body = ", ".join(f'"{k}": {t if r else "NotRequired[" + t + "]"}' for k, t, r in items)
        return f'{name} = TypedDict("{name}", {{{body}}})\n'
    lines = [f"class {name}(TypedDict):"]
    if not items:
        lines.append("    pass")
    for key, text, req in items:
        lines.append(f"    {key}: {text if req else 'NotRequired[' + text + ']'}")
    return "\n".join(lines) + "\n"


def main(argv: List[str]) -> int:
    if len(argv) != 1:
        print(__doc__)
        return 2
    mod = importlib.import_module("e2b.sandbox.mcp")
    parts = [HEADER]
    for name, cls in classes_in_order(mod):
        parts.append("\n\n" + render(name, cls))
    with open(argv[0], "w") as f:
        f.write("".join(parts))
    print(f"wrote {len(parts) - 1} classes to {argv[0]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
