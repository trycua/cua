/** A caller's RUSTUP_TOOLCHAIN would override the tool's pinned nightly. */
function withoutToolchainOverride(env: NodeJS.ProcessEnv): NodeJS.ProcessEnv {
  const { RUSTUP_TOOLCHAIN: _ignored, ...rest } = env;
  return rest;
}

function buildDump(): Dump {
  const target = path.join(TOOL_DIR, 'target');
  const out = path.join(target, 'dump.json');
  // cwd = the tool dir, so rustup picks its pinned nightly (rust-toolchain.toml).
  execFileSync(
    'cargo',
    [
      'run',
      '--quiet',
      '--release',
      '--',
      '--workspace',
      path.join(REPO_ROOT, 'libs', 'cua'),
      '--target-dir',
      path.join(target, 'crates'),
      '--out',
      out,
      ...CRATES,
    ],
    { cwd: TOOL_DIR, stdio: 'inherit', env: withoutToolchainOverride(process.env) }
  );
  return JSON.parse(fs.readFileSync(out, 'utf-8'));
}

function main(): void {
  const args = process.argv.slice(2);
  const checkOnly = isCheckMode(args);
  const dumpIndex = args.indexOf('--dump');
  const dump: Dump =
    dumpIndex >= 0 ? JSON.parse(fs.readFileSync(args[dumpIndex + 1], 'utf-8')) : buildDump();
  const version = fs.readFileSync(path.join(REPO_ROOT, 'libs', 'cua', 'VERSION'), 'utf-8').trim();
  const drift = syncFiles(renderAll(dump, version), checkOnly, [OUTPUT_DIR], GENERATOR);
  finish('Rust crate', drift, checkOnly, GENERATOR);
}

if (require.main === module) main();
